def _build_ticker(data: dict, lang: str) -> list[str]:
    nl = data["name_lookup"]
    lines: list[str] = []
    for c in data["top_countries"]:
        # top_countries는 _gather()가 담아온 한국어 이름을 갖고 있다 —
        # 지역화된 name_lookup을 우선한다(안 그러면 티커만 한국어로 남는다).
        name = nl.get(c["country"]) or c.get("name", c["country"])
        score = c.get("risk_score")
        tier = _tier_label(lang, c.get("tier"))
        lines.append(_TICKER[lang].format(name=name, score=score, tier=tier))
    for a in data["alerts"][:3]:
        # 경보 라벨은 한국어로 조립돼 오므로 표시 언어로 옮긴다 —
        # 안 그러면 문장은 번역됐는데 티커만 한국어로 남는다.
        from .name_i18n import alert_label
        lines.append(alert_label(a.get("label", ""), lang) or "")
    return [l for l in lines if l]


