def _threat_lines(fmt_id: str, ev: dict, nl: dict, lang: str, idx: int):
    """포맷별로 같은 사실을 다른 방송 말투로 푼다. (script, dialogue) 반환 —
    dialogue는 2인 대담 포맷에서만 채워지고 나머지는 None. 숫자·등급·출처는 불변."""
    disease = _disease_name(ev.get("disease"), lang) or _UNSPECIFIED[lang]
    where = _country_names(ev.get("countries", []), nl, lang)
    tier = _tier_label(lang, ev.get("tier"))
    score = ev.get("merged_score")
    n = ev.get("source_count", 0)
    ctx = {"disease": disease, "where": where, "tier": tier, "n": n, "score": score}
    sp = _SPEAKER[lang]

    def line(key: str) -> str:
        return _LINES[key][lang].format(**ctx)

    if fmt_id == "deepdive":
        return line("deepdive_lead" if idx == 1 else "deepdive_more"), None

    if fmt_id == "field":
        # 앵커가 현장을 연결하면 현장기자가 리포트하는 구조.
        q, a = line("field_q"), line("field_a")
        dialogue = [{"speaker": "anchor", "text": q}, {"speaker": "reporter", "text": a}]
        return f"[{sp['anchor']}] {q} [{sp['reporter']}] {a}", dialogue

    if fmt_id == "data":
        return line("data"), None

    if fmt_id == "duo":
        q, a = line("duo_q"), line("duo_a")
        dialogue = [{"speaker": "anchor", "text": q}, {"speaker": "cohost", "text": a}]
        return f"[{sp['anchor']}] {q} [{sp['cohost']}] {a}", dialogue

    return line("breaking"), None


