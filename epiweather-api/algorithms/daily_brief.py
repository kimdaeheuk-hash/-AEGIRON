def generate_daily_brief(lang: str = "ko", api_key: str | None = None,
                         today: str | None = None, fmt: str | None = None) -> dict:
    """방송 러시트 한 벌을 조립한다. lang: 'ko'|'en'. fmt로 포맷을 고정하지 않으면
    날짜별로 다른 작가(포맷)가 로테이션돼 매일 형태가 달라진다. api_key가 있으면 앵커
    대본을 Claude로 다듬고, 없거나 실패하면 결정론적 템플릿을 그대로 쓴다(generation_method 표시)."""
    lang = lang if lang in SUPPORTED_LANGS else FALLBACK_LANG
    today = today or dt.date.today().isoformat()
    fmt_spec = _select_format(today, fmt)

    data = _gather()
    data = _localized(data, lang)   # 국가명을 요청 언어 표기로
    segments = _build_segments(data, lang, fmt_spec)
    # quiet_day는 '실제 위협' 기준 — 홍보 세그먼트를 붙이기 전에 판정한다.
    quiet = all(s["kind"] == "quiet" for s in segments)
    segments = segments + [_promo_segment(fmt_spec, lang, today)]  # 작가가 뉴스 끝에 아이기론 소개
    headline, summary = _headline(data, lang, quiet, fmt_spec)
    ticker = _build_ticker(data, lang)

    closing = _CLOSING[lang]

    presenters = [_presenter_spec(today, lang, _ANCHOR)]
    if fmt_spec["id"] == "duo":
        presenters.append(_presenter_spec(today, lang, _pick(_ANALYSTS, today)))  # 분석위원 3인 중 로테이션
    elif fmt_spec["id"] == "field":
        presenters.append(_presenter_spec(today, lang, _pick(_REPORTERS, today)))  # 현장기자 남녀 로테이션

    brief = {
        "date": today,
        "lang": lang,
        "program_name": _PROGRAM_NAME[lang],
        "format": {
            "id": fmt_spec["id"],
            "name": fmt_spec["name"][lang],
            "host_mode": fmt_spec["host_mode"],
            "description": fmt_spec["desc"][lang],
        },
        "available_formats": [
            {"id": f["id"], "name": f["name"][lang], "description": f["desc"][lang]}
            for f in _FORMATS
        ],
        "presenter": presenters[0],          # 하위호환(단일 진행자 소비자용)
        "presenters": presenters,            # 대담 포맷은 앵커+분석위원 2인
        "is_official_alert": False,
        "quiet_day": quiet,
        "headline": headline,
        "summary": summary,
        "segments": segments,
        "ticker": ticker,
        "disclosure": _DISCLOSURE[lang],
        "closing": closing,
        "generation_method": "template_fallback",
    }

    if api_key:
        polished = _polish_with_llm(brief, lang, fmt_spec, api_key)
        if polished is not None:
            brief = polished
            brief["generation_method"] = "llm_polished"

    # ── 특수 섹션 ────────────────────────────────────────────────────────
    # 84개 모듈 중 이 파일이 쓰던 건 4개뿐이었다. 극지·조용해진 곳·7일 예보·
    # 설명 불가 신호는 매일 값이 달라지는데 브리핑에 실리지 않아, 7일 연속으로
    # 헤드라인이 똑같았다(2026-08-26 실측, 연속 유사도 88~89%).
    #
    # ★ LLM 폴리시 **뒤에** 붙인다 ★ 이 칸들은 실측 숫자라 문장을 다듬는 과정에서
    # 값이 바뀌면 안 된다. 폴리시는 앵커 대본만 손대게 둔다.
    build_special_sections = _import_sections()
    brief["special_sections"] = build_special_sections(
        lang, on_error=lambda name, e: brief.setdefault("special_section_errors", []).append(
            {"section": name, "error": f"{type(e).__name__}: {e}"}))

    # 팟캐스트 에피소드(오디오용)는 폴리시가 끝난 최종 대본 기준으로 조립한다.
    brief["podcast"] = _podcast_block(
        brief["presenters"], brief["segments"], brief["headline"],
        brief["summary"], brief["closing"], brief["disclosure"], lang,
    )
    return brief
