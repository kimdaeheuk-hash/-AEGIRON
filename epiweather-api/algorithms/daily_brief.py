def _assert_lang_tables() -> None:
    """모든 언어 표가 SUPPORTED_LANGS를 빠짐없이 담고 있는지 **가져오기 시점에** 확인한다.

    왜 이렇게까지 하는가: 표 하나에 키를 빠뜨리면 그 자리만 다른 언어로 튀어나오는데,
    예외도 로그도 없이 조용히 섞인다. 실제로 이 모듈은 `lang`이 ko가 아니면 무조건
    영어를 쓰는 구조였고, 그래서 프랑스어 요청이 **오류 없이 한국어로 되돌아왔다.**
    조용히 틀리는 실패를 배포 후에 발견하지 않으려면 여기서 죽는 편이 낫다.
    """
    tables = {
        "_TIER_LABEL": _TIER_LABEL, "_DISCLOSURE": _DISCLOSURE,
        "_PROGRAM_NAME": _PROGRAM_NAME, "_ETHNICITY": _ETHNICITY,
        "_MULTI_REGION": _MULTI_REGION, "_AND_MORE": _AND_MORE, "_UNSPECIFIED": _UNSPECIFIED,
        "_SPEAKER": _SPEAKER, "_QUIET_SCRIPT": _QUIET_SCRIPT, "_QUIET_DEFAULT": _QUIET_DEFAULT,
        "_QUIET_LOWER": _QUIET_LOWER, "_FUTURE_TAG": _FUTURE_TAG, "_PROMO_Q": _PROMO_Q,
        "_PROMO_LOWER": _PROMO_LOWER, "_PROMO_LOWER_FUTURE": _PROMO_LOWER_FUTURE,
        "_PROMO_LEADIN": _PROMO_LEADIN, "_TICKER": _TICKER, "_HEAD_QUIET": _HEAD_QUIET,
        "_HEAD_QUIET_SUB": _HEAD_QUIET_SUB, "_HEAD_MAIN": _HEAD_MAIN,
        "_HEAD_MAIN_SUB": _HEAD_MAIN_SUB, "_CONSISTENCY_NOTE": _CONSISTENCY_NOTE,
        "_AUDIO_LOCALE": _AUDIO_LOCALE, "_PODCAST_NOTE": _PODCAST_NOTE,
        "_LANG_WORD": _LANG_WORD, "_CLOSING": _CLOSING,
    }
    missing = []
    for name, table in tables.items():
        for lang in SUPPORTED_LANGS:
            if lang not in table:
                missing.append(f"{name}[{lang!r}]")
    for key, table in _LINES.items():
        for lang in SUPPORTED_LANGS:
            if lang not in table:
                missing.append(f"_LINES[{key!r}][{lang!r}]")
    for key, table in _QUIET_DIALOGUE.items():
        for lang in SUPPORTED_LANGS:
            if lang not in table:
                missing.append(f"_QUIET_DIALOGUE[{key!r}][{lang!r}]")
    for persona in [_ANCHOR, *_ANALYSTS, *_REPORTERS]:
        for lang in SUPPORTED_LANGS:
            if lang not in persona["name"]:
                missing.append(f"진행자 {persona['id']} 이름[{lang!r}]")
    for fmt in _FORMATS:
        for lang in SUPPORTED_LANGS:
            if lang not in fmt["name"]:
                missing.append(f"포맷 {fmt['id']} name[{lang!r}]")
            if lang not in fmt["desc"]:
                missing.append(f"포맷 {fmt['id']} desc[{lang!r}]")
    for i, point in enumerate(_PROMO_POINTS):
        for lang in SUPPORTED_LANGS:
            if lang not in point:
                missing.append(f"_PROMO_POINTS[{i}][{lang!r}]")
    if missing:
        raise RuntimeError(
            "번역 누락 — 이대로 두면 그 자리만 다른 언어로 조용히 섞여 나간다: "
            + ", ".join(missing[:20])
            + (f" 외 {len(missing) - 20}건" if len(missing) > 20 else "")
        )


_assert_lang_tables()


