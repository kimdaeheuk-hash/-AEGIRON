def _country_names(codes: list[str], name_lookup: dict[str, str], lang: str) -> str:
    if not codes:
        return _MULTI_REGION[lang]
    labels = [name_lookup.get(c, c) for c in codes[:3]]
    joined = ", ".join(labels)
    if len(codes) > 3:
        joined += _AND_MORE[lang].format(n=len(codes) - 3)
    return joined


def _gather() -> dict:
    """이미 계산된 결과를 모은다 — 여기서 점수를 새로 만들지 않는다."""
    from .event_dedup import dedupe_events
    from .alerts import refresh_alerts
    from .country_risk import rank_countries

    events = dedupe_events()
    # 등급이 매겨진(합류점수 있는) 위협만, 점수 높은 순으로.
    threats = [e for e in events if e.get("merged_score") is not None][:_MAX_SEGMENTS]

    try:
        alerts = refresh_alerts().get("dashboard", {}).get("top", [])
    except Exception:
        alerts = []

    ranked = rank_countries().get("countries", [])
    name_lookup = {c["country"]: c.get("name", c["country"]) for c in ranked}
    top_countries = [c for c in ranked if c.get("has_signal")][:3]

    return {
        "threats": threats,
        "alerts": alerts,
        "top_countries": top_countries,
        "name_lookup": name_lookup,
    }


