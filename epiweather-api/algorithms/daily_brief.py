"""일일 브리핑(㊱) — 홈페이지 실시간 뉴스·팟캐스트 대본·유튜브 방송 러시트가
공통으로 읽는 '하나의 재료'.

왜 이 층이 필요한가
-------------------
매시간 쌓이는 신호(중복제거 이벤트·경보·국가위험)를 사람이 매번 손으로 요약해
뉴스/오디오/영상으로 만드는 건 불가능하다. 이 모듈은 이미 계산된 결과를 모아
'방송 러시트(rundown)' 한 벌로 조립한다:
  - headline / summary  : 뉴스 헤드라인·리드
  - segments[]          : 앵커 대본(anchor_script) + 자막(lower_third) + 화면지시(visual_cue)
  - ticker[]            : 하단 스크롤 자막
  - disclosure/closing  : 고지·마무리
이 한 벌이 곧 팟캐스트 TTS 대본이자 유튜브 방송 대본이자 홈페이지 뉴스카드다.
페이퍼클립 같은 자동화 플랫폼은 이 JSON만 받아서 영상·오디오를 찍어낸다.

★ 정직성 경계선 ★
- is_official_alert=False. 이건 '공개 데이터 자동 요약'이지 보건당국 공식 경보가
  아니다. disclosure에 못박고, AI 생성물임을 항상 표시한다.
- 조용한 날은 조용하게. 새 위협이 없으면 없다고 말한다 — 방송을 채우려고 없는
  위기를 지어내지 않는다(quiet_day=True).
- 앵커 대본은 ANTHROPIC_API_KEY가 있으면 Claude로 자연스럽게 다듬고, 없거나
  실패하면 결정론적 템플릿으로 폴백한다. 어느 쪽인지 generation_method로 정직하게
  표시한다(교차언어 클러스터링·기존 폴백 철학과 동일).
- 숫자·출처는 전부 이미 계산된 실데이터에서 온다. 이 모듈은 표현만 만들지 점수를
  새로 지어내지 않는다.
"""
