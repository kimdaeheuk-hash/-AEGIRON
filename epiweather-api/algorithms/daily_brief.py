def _build_segments(data: dict, lang: str, fmt: dict) -> list[dict]:
    segs: list[dict] = []
    nl = data["name_lookup"]
    fmt_id = fmt["id"]

    for i, ev in enumerate(data["threats"], 1):
        script, dialogue = _threat_lines(fmt_id, ev, nl, lang, i)
        disease = _disease_name(ev.get("disease"), lang) or _UNSPECIFIED[lang]
        where = _country_names(ev.get("countries", []), nl, lang)
        tier = _tier_label(lang, ev.get("tier"))
        seg = {
            "segment_id": f"threat_{i}",
            "kind": "threat",
            "anchor_script": script,
            "lower_third": f"{disease} · {where} · {tier}",
            "visual_cue": f"map_focus:{','.join(ev.get('countries', [])) or 'world'}",
            "tier": ev.get("tier"),
            "score": ev.get("merged_score"),
            "sources": ev.get("sources", []),
            "countries": ev.get("countries", []),
        }
        if dialogue is not None:
            seg["dialogue"] = dialogue  # 2인 대담 — 화자별 대사
        segs.append(seg)

    # 위협이 하나도 없으면 조용한 날 세그먼트(방송을 억지로 채우지 않는다).
    if not segs:
        script = _QUIET_SCRIPT[lang].get(fmt_id, _QUIET_DEFAULT[lang])
        lower = _QUIET_LOWER[lang]
        seg = {
            "segment_id": "quiet",
            "kind": "quiet",
            "anchor_script": script,
            "lower_third": lower,
            "visual_cue": "map_focus:world",
            "tier": None,
            "score": None,
            "sources": [],
            "countries": [],
        }
        if fmt_id in _QUIET_DIALOGUE:
            # 대담·현장 포맷은 조용한 날도 대화체로
            q, a = _QUIET_DIALOGUE[fmt_id][lang]
            responder = "cohost" if fmt_id == "duo" else "reporter"
            seg["dialogue"] = [
                {"speaker": "anchor", "text": q},
                {"speaker": responder, "text": a},
            ]
        segs.append(seg)

    return segs


