def _pick(pool: list[dict], today: str, salt: int = 0) -> dict:
    """날짜별 결정론적 로테이션(하루 안에서는 고정, 날이 바뀌면 다른 사람)."""
    try:
        ordinal = dt.date.fromisoformat(today).toordinal()
    except ValueError:
        ordinal = 0
    return pool[(ordinal + salt) % len(pool)]


